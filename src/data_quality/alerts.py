"""
src/data_quality/alerts.py
--------------------------
Market Activity Alerts Engine.
Applies configurable statistical rules to detect unusual price variations and volume surges.

TRANSPARENCY NOTICE:
Alerts generated by this module are deterministic, rule-based statistical calculations.
No predictive Machine Learning model is claimed. These indicators are designed for
data pipeline monitoring and market activity screening, NOT investment advice.
"""

from typing import List, Dict, Any
from datetime import datetime

class MarketActivityAlertEngine:
    def __init__(
        self,
        price_change_threshold_pct: float = 2.50,
        volume_surge_multiplier: float = 1.25,
        ma_divergence_threshold_pct: float = 3.00
    ):
        self.price_change_threshold_pct = price_change_threshold_pct
        self.volume_surge_multiplier = volume_surge_multiplier
        self.ma_divergence_threshold_pct = ma_divergence_threshold_pct

    def evaluate_records(
        self,
        records: List[Dict[str, Any]],
        historical_averages: Dict[str, Dict[str, float]] = None
    ) -> List[Dict[str, Any]]:
        """
        Evaluates a list of stock records against configurable statistical threshold rules.
        """
        alerts = []
        historical_averages = historical_averages or {}

        for rec in records:
            symbol = rec.get("symbol", "UNKNOWN")
            timestamp = rec.get("timestamp") or rec.get("last_updated") or datetime.now().isoformat()
            price = rec.get("daily_close")
            pct_change = rec.get("percent_change") or rec.get("daily_change")
            volume = rec.get("daily_volume")
            ma15 = rec.get("ma_15")

            # 1. Price Volatility Check
            if pct_change is not None:
                abs_change = abs(pct_change)
                if abs_change >= self.price_change_threshold_pct:
                    direction = "Rally" if pct_change > 0 else "Drop"
                    alerts.append({
                        "stock": symbol,
                        "alert_type": f"PRICE_VOLATILITY_{direction.upper()}",
                        "severity": "HIGH" if abs_change >= 4.0 else "MEDIUM",
                        "observed_value": f"{pct_change:+.2f}%",
                        "threshold": f"|Δ| >= {self.price_change_threshold_pct:.2f}%",
                        "timestamp": timestamp,
                        "rule_type": "Deterministic Statistical Threshold (Rule-Based)",
                        "reason": f"Intraday price moved {pct_change:+.2f}%, surpassing the configured statistical boundary of ±{self.price_change_threshold_pct:.2f}%."
                    })

            # 2. Volume Surge Check
            hist_avg_vol = historical_averages.get(symbol, {}).get("avg_volume", 25_000_000)
            if volume is not None and hist_avg_vol > 0:
                surge_ratio = volume / hist_avg_vol
                if surge_ratio >= self.volume_surge_multiplier:
                    alerts.append({
                        "stock": symbol,
                        "alert_type": "VOLUME_SURGE",
                        "severity": "HIGH" if surge_ratio >= 1.8 else "MEDIUM",
                        "observed_value": f"{volume:,} ({surge_ratio:.2f}x avg)",
                        "threshold": f">= {self.volume_surge_multiplier:.2f}x baseline ({hist_avg_vol:,.0f})",
                        "timestamp": timestamp,
                        "rule_type": "Volume Multiplier Anomaly (Statistical Ratio)",
                        "reason": f"Trading volume of {volume:,} exceeded historical baseline of {hist_avg_vol:,.0f} by {surge_ratio:.2f}x."
                    })

            # 3. Moving Average Divergence
            if price is not None and ma15 is not None and ma15 > 0:
                divergence_pct = ((price - ma15) / ma15) * 100
                if abs(divergence_pct) >= self.ma_divergence_threshold_pct:
                    pos_neg = "Above" if divergence_pct > 0 else "Below"
                    alerts.append({
                        "stock": symbol,
                        "alert_type": f"MA15_DIVERGENCE_{pos_neg.upper()}",
                        "severity": "LOW",
                        "observed_value": f"${price:.2f} ({divergence_pct:+.2f}% vs MA15 ${ma15:.2f})",
                        "threshold": f"|divergence| >= {self.ma_divergence_threshold_pct:.2f}%",
                        "timestamp": timestamp,
                        "rule_type": "Trend Divergence Indicator (Technical Rule)",
                        "reason": f"Closing price ${price:.2f} diverged from 15-day moving average (${ma15:.2f}) by {divergence_pct:+.2f}%."
                    })

        return alerts
